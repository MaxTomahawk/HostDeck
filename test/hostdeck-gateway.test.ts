import assert from 'node:assert/strict';
import {test} from 'node:test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import http from 'node:http';
import {generateKeyPair,exportJWK,SignJWT,createLocalJWKSet} from 'jose';
import {toNodeHandler} from '@modelcontextprotocol/node';
import {AuditLog,TokenAuthority,PolicyGate,type Grant} from '../src/hostdeck/security.js';
import {HostDeckFacade,createHttpBoundary} from '../src/hostdeck/gateway.js';
import {UserRuntime} from '../src/hostdeck/user-runtime.js';

test('actual HTTP MCP dispatch enforces signed tokens, current grants, strict contracts and scoped discovery',async t=>{
  const directory=await fs.mkdtemp(path.join(os.tmpdir(),'hostdeck-gateway-'));
  const audit=await AuditLog.open(path.join(directory,'audit'));
  let runtime:UserRuntime;
  t.after(async()=>{await runtime?.dispose();audit.close();await fs.rm(directory,{recursive:true,force:true});});
  const {privateKey,publicKey}=await generateKeyPair('RS256');
  const issuer='https://issuer.example',resource='https://hostdeck.example/mcp';
  const authority=new TokenAuthority({issuer,audience:resource,jwks:createLocalJWKSet({keys:[{...await exportJWK(publicKey),kid:'fixture'}]})});
  const now=Math.floor(Date.now()/1000);
  const token=await new SignJWT({sub:'fixture',client_id:'client',scope:'files:read files:write'}).setProtectedHeader({alg:'RS256',typ:'at+jwt',kid:'fixture'}).setIssuer(issuer).setAudience(resource).setIssuedAt(now).setExpirationTime(now+300).sign(privateKey);
  let grants:Grant[]=[{issuer,subject:'fixture',clientId:'client',deviceId:'device',executorId:'executor',scopes:['files:read','files:write'],expiresAt:now+300,revision:'1',broadUserAuthority:true,sessionIds:[1]}];
  const gate=new PolicyGate(authority,audit,async()=>grants);
  let facade:HostDeckFacade;
  runtime=await UserRuntime.create({workspace:directory,deviceId:'device',environment:{},shells:{},authorize:async(name,args)=>{await facade.reauthorize(name,args);return true;}});
  facade=new HostDeckFacade({deviceId:'device',executorId:'executor',gate,adapters:[{implementedTools:runtime.implementedTools,handle:(name,args)=>runtime.invoke(name,args)}]});
  const allowedHosts:string[]=[];
  const boundary=createHttpBoundary(facade,authority,{issuer,resource,allowedHosts,allowedOrigins:[]});
  // Use a real socket; the request boundary sees the exact configured Host header.
  const nodeHandler=toNodeHandler(boundary);
  const server=http.createServer((req,res)=>void nodeHandler(req,res));
  await new Promise<void>(resolve=>server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{await boundary.close();await new Promise<void>(resolve=>server.close(()=>resolve()));});
  const port=(server.address() as {port:number}).port;
  allowedHosts.push(`127.0.0.1:${port}`);
  let id=0;
  const rpc=async(method:string,params:unknown={},headers:Record<string,string>={})=>{
    if(headers['mcp-protocol-version']==='2026-07-28') params={...(params as object),_meta:{'io.modelcontextprotocol/protocolVersion':'2026-07-28','io.modelcontextprotocol/clientCapabilities':{}}};
    const response=await fetch(`http://127.0.0.1:${port}/mcp`,{method:'POST',headers:{authorization:`Bearer ${token}`,'content-type':'application/json',accept:'application/json, text/event-stream','mcp-protocol-version':'2025-11-25',...headers},body:JSON.stringify({jsonrpc:'2.0',id:++id,method,params})});
    const text=await response.text();
    const data=text.startsWith('event:')||text.startsWith('data:')?JSON.parse(text.split('\n').find(line=>line.startsWith('data:'))!.slice(5)):JSON.parse(text);
    return {status:response.status,data};
  };
  const listed=await rpc('tools/list');
  assert.equal(listed.status,200);
  assert.ok(listed.data.result.tools.some((x:{name:string})=>x.name==='hostdeck_write_file'));
  assert.ok(!listed.data.result.tools.some((x:{name:string})=>x.name==='hostdeck_start_process'));
  const modern=await rpc('tools/list',{}, {'mcp-protocol-version':'2026-07-28','mcp-method':'tools/list'});
  assert.equal(modern.status,200);
  assert.ok(modern.data.result.tools.some((x:{name:string})=>x.name==='hostdeck_read_file'));
  const result=await rpc('tools/call',{name:'hostdeck_write_file',arguments:{device_id:'device',path:'actual.txt',content:'actual HTTP write'}});
  assert.equal(result.data.result.isError,undefined);
  assert.equal(await fs.readFile(path.join(directory,'actual.txt'),'utf8'),'actual HTTP write');
  const malformed=await rpc('tools/call',{name:'hostdeck_write_file',arguments:{device_id:'device',path:'bad.txt',content:'no',unexpected:true}});
  assert.equal(malformed.data.result.isError,true);
  await assert.rejects(fs.stat(path.join(directory,'bad.txt')));
  const denied=await fetch(`http://127.0.0.1:${port}/mcp`,{method:'POST',headers:{authorization:'Bearer invalid'}});
  assert.equal(denied.status,401);
  const rebinding=await fetch(`http://127.0.0.1:${port}/mcp`,{method:'POST',headers:{origin:'https://evil.example'}});
  assert.equal(rebinding.status,403);
  grants=[];
  const revoked=await rpc('tools/call',{name:'hostdeck_write_file',arguments:{device_id:'device',path:'actual.txt',content:'unauthorized'}});
  assert.equal(revoked.data.result.isError,true);
  assert.equal(await fs.readFile(path.join(directory,'actual.txt'),'utf8'),'actual HTTP write');
  assert.equal((await rpc('tools/list')).data.result.tools.length,0);
});
