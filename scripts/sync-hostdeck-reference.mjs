#!/usr/bin/env node
/** Canonical source reference only; no server startup, discovery or authority. */
import {readFile, writeFile} from 'node:fs/promises';
import {contractVersion, listToolContracts, listResourceTemplates, listPrompts}
  from '../src/hostdeck/contracts.ts';

const target = new URL('../plugin/hostdeck/skills/hostdeck-operations/references/contracts.md', import.meta.url);
const args = process.argv.slice(2);
if (args.length > 1 || (args.length && !['--check', '--write'].includes(args[0]))) {
  process.stderr.write('Use --check (default, read-only) or --write.\n');
  process.exitCode = 2;
} else {
  try {
    const contracts = listToolContracts();
    const lines = [
      '# HostDeck source contract index', '',
      '<!-- Generated by scripts/sync-hostdeck-reference.mjs; do not edit. -->', '',
      `Contract revision: ${contractVersion}. Source definitions: ${contracts.length}.`, '',
      'This is a source index, not installed or authorized tool discovery. Use only',
      'the connected server\'s actual tools and schemas. Required scopes are necessary',
      'conditions, not grants; device/session/effect checks still apply. Unknown',
      'host resource or prompt support must remain unknown, not accepted.', '',
      'Regenerate with `node --import tsx scripts/sync-hostdeck-reference.mjs --write`;',
      'validate without writing by replacing `--write` with `--check`.', '',
    ];
    for (const domain of [...new Set(contracts.map(c => c.domain))].sort()) {
      lines.push(`## ${domain}`, '', '| Tool | Effect | Required scopes |', '|---|---|---|');
      for (const contract of contracts.filter(c => c.domain === domain).sort((a,b) => a.name.localeCompare(b.name)))
        lines.push(`| \`${contract.name}\` | ${contract.effect} | ${contract.requiredScopes.map(s => `\`${s}\``).join(', ')} |`);
      lines.push('');
    }
    lines.push('## Resource templates', '', '| URI template | Required scopes |', '|---|---|');
    for (const resource of listResourceTemplates())
      lines.push(`| \`${resource.uriTemplate}\` | ${resource.requiredScopes.map(s => `\`${s}\``).join(', ')} |`);
    lines.push('', '## Prompts', '');
    for (const prompt of listPrompts()) lines.push(`- \`${prompt.name}\`: ${prompt.description}`);
    lines.push('', 'The full manager opens only through an explicitly requested',
      '`hostdeck_open_manager` call and its advertised `ui://hostdeck/management/v2`',
      'resource. Ordinary calls do not open it. The obsolete unversioned resource',
      'is refused by the current server. Source metadata does not prove host rendering.', '');
    const expected = lines.join('\n');
    if (args[0] === '--write') {
      await writeFile(target, expected, 'utf8');
      process.stdout.write(`HostDeck reference generated: ${contracts.length} source definitions.\n`);
    } else {
      const actual = await readFile(target, 'utf8').catch(error => {
        if (error.code === 'ENOENT') return '';
        throw error;
      });
      if (actual.replace(/\r\n/g, '\n') !== expected) {
        process.stderr.write('HostDeck source reference is stale; regenerate explicitly with --write.\n');
        process.exitCode = 1;
      } else process.stdout.write(`HostDeck reference matches ${contracts.length} source definitions.\n`);
    }
  } catch {
    process.stderr.write('HostDeck reference inspection failed; no server or external operation was started.\n');
    process.exitCode = 2;
  }
}
